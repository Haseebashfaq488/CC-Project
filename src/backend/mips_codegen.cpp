#include "mips_codegen.h"
#include <iostream>
#include <sstream>
#include <cctype>

MIPSCodeGenerator::MIPSCodeGenerator() : str_counter(0) {}

bool MIPSCodeGenerator::isNumber(const std::string& s) const {
    if (s.empty()) return false;
    size_t start = (s[0] == '-' || s[0] == '+') ? 1 : 0;
    if (start == s.length()) return false;
    for (size_t i = start; i < s.length(); ++i) {
        if (!std::isdigit(s[i])) return false;
    }
    return true;
}

void MIPSCodeGenerator::collectData(const std::vector<TACInstruction>& instrs) {
    string_literals.clear();
    declared_vars.clear();
    array_sizes.clear();
    str_counter = 0;

    for (const auto& instr : instrs) {
        // Find string literals in PRINT or assignments
        if (instr.op == "PRINT" && !instr.arg1.empty() && instr.arg1.front() == '"') {
            if (string_literals.find(instr.arg1) == string_literals.end()) {
                string_literals[instr.arg1] = "str_" + std::to_string(str_counter++);
            }
        }
        if (instr.op == "=" && !instr.arg1.empty() && instr.arg1.front() == '"') {
            if (string_literals.find(instr.arg1) == string_literals.end()) {
                string_literals[instr.arg1] = "str_" + std::to_string(str_counter++);
            }
        }

        // Collect array allocations
        if (instr.op == "ALLOC_ARRAY") {
            int sz = std::stoi(instr.arg1);
            array_sizes[instr.result] = sz;
            continue;
        }

        // Collect variables and temporaries
        if (!instr.result.empty() && instr.op != "LABEL" && instr.op != "GOTO" &&
            instr.op != "IF_FALSE" && instr.op != "IF_TRUE") {
            declared_vars.insert(instr.result);
        }
        if (!instr.arg1.empty() && !isNumber(instr.arg1) && instr.arg1.front() != '"' &&
            instr.arg1.front() != '\'') {
            declared_vars.insert(instr.arg1);
        }
        if (!instr.arg2.empty() && !isNumber(instr.arg2) && instr.arg2.front() != '"' &&
            instr.arg2.front() != '\'') {
            declared_vars.insert(instr.arg2);
        }
    }
}

std::string MIPSCodeGenerator::loadOperand(const std::string& operand, const std::string& reg) {
    if (isNumber(operand)) {
        return "    li " + reg + ", " + operand + "\n";
    }
    return "    lw " + reg + ", " + operand + "\n";
}

std::string MIPSCodeGenerator::generate(const std::vector<TACInstruction>& instrs) {
    collectData(instrs);
    std::ostringstream ss;

    ss << "# ========================================================\n";
    ss << "#  MIPS32 Assembly generated by YaarLang Compiler (yaarc)\n";
    ss << "#  Compatible with MARS 4.5 and SPIM Simulators\n";
    ss << "# ========================================================\n\n";

    // Data section
    ss << ".data\n";
    ss << "newline: .asciiz \"\\n\"\n";

    for (const auto& pair : string_literals) {
        ss << pair.second << ": .asciiz " << pair.first << "\n";
    }

    for (const auto& pair : array_sizes) {
        ss << pair.first << ": .space " << (pair.second * 4) << "\n";
    }

    for (const auto& var : declared_vars) {
        if (array_sizes.find(var) == array_sizes.end()) {
            ss << var << ": .word 0\n";
        }
    }

    // Text section
    ss << "\n.text\n";
    ss << ".globl main\n\n";

    for (const auto& instr : instrs) {
        if (instr.op == "LABEL") {
            ss << instr.result << ":\n";
            continue;
        }

        if (instr.op == "=" || instr.op == "ASSIGN") {
            if (!instr.arg1.empty() && instr.arg1.front() == '"') {
                std::string str_lbl = string_literals[instr.arg1];
                ss << "    la $t0, " << str_lbl << "\n";
                ss << "    sw $t0, " << instr.result << "\n";
            } else {
                ss << loadOperand(instr.arg1, "$t0");
                ss << "    sw $t0, " << instr.result << "\n";
            }
            continue;
        }

        if (instr.op == "+" || instr.op == "-" || instr.op == "*" ||
            instr.op == "/" || instr.op == "%") {
            ss << loadOperand(instr.arg1, "$t0");
            ss << loadOperand(instr.arg2, "$t1");
            if (instr.op == "+") ss << "    add $t2, $t0, $t1\n";
            else if (instr.op == "-") ss << "    sub $t2, $t0, $t1\n";
            else if (instr.op == "*") ss << "    mul $t2, $t0, $t1\n";
            else if (instr.op == "/") ss << "    div $t0, $t1\n    mflo $t2\n";
            else if (instr.op == "%") ss << "    rem $t2, $t0, $t1\n";
            ss << "    sw $t2, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "==" || instr.op == "!=" || instr.op == "<" ||
            instr.op == "<=" || instr.op == ">" || instr.op == ">=") {
            ss << loadOperand(instr.arg1, "$t0");
            ss << loadOperand(instr.arg2, "$t1");
            if (instr.op == "==") ss << "    seq $t2, $t0, $t1\n";
            else if (instr.op == "!=") ss << "    sne $t2, $t0, $t1\n";
            else if (instr.op == "<") ss << "    slt $t2, $t0, $t1\n";
            else if (instr.op == "<=") ss << "    sle $t2, $t0, $t1\n";
            else if (instr.op == ">") ss << "    sgt $t2, $t0, $t1\n";
            else if (instr.op == ">=") ss << "    sge $t2, $t0, $t1\n";
            ss << "    sw $t2, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "&&" || instr.op == "||") {
            ss << loadOperand(instr.arg1, "$t0");
            ss << loadOperand(instr.arg2, "$t1");
            if (instr.op == "&&") ss << "    and $t2, $t0, $t1\n";
            else if (instr.op == "||") ss << "    or $t2, $t0, $t1\n";
            ss << "    sw $t2, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "!") {
            ss << loadOperand(instr.arg1, "$t0");
            ss << "    xori $t2, $t0, 1\n";
            ss << "    sw $t2, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "IF_FALSE") {
            ss << loadOperand(instr.arg1, "$t0");
            ss << "    beqz $t0, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "IF_TRUE") {
            ss << loadOperand(instr.arg1, "$t0");
            ss << "    bnez $t0, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "GOTO") {
            ss << "    j " << instr.result << "\n";
            continue;
        }

        if (instr.op == "PRINT") {
            if (!instr.arg1.empty() && instr.arg1.front() == '"') {
                std::string str_lbl = string_literals[instr.arg1];
                ss << "    la $a0, " << str_lbl << "\n";
                ss << "    li $v0, 4\n    syscall\n";
            } else {
                ss << loadOperand(instr.arg1, "$a0");
                ss << "    li $v0, 1\n    syscall\n";
            }
            // print newline
            ss << "    la $a0, newline\n    li $v0, 4\n    syscall\n";
            continue;
        }

        if (instr.op == "READ") {
            ss << "    li $v0, 5\n    syscall\n";
            ss << "    sw $v0, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "ARRAY_STORE") {
            ss << loadOperand(instr.result, "$t0"); // value
            ss << loadOperand(instr.arg2, "$t1");   // index
            ss << "    sll $t1, $t1, 2\n";
            ss << "    sw $t0, " << instr.arg1 << "($t1)\n";
            continue;
        }

        if (instr.op == "ARRAY_LOAD") {
            ss << loadOperand(instr.arg2, "$t1");   // index
            ss << "    sll $t1, $t1, 2\n";
            ss << "    lw $t0, " << instr.arg1 << "($t1)\n";
            ss << "    sw $t0, " << instr.result << "\n";
            continue;
        }

        if (instr.op == "CALL") {
            ss << "    jal " << instr.arg1 << "\n";
            if (!instr.result.empty()) {
                ss << "    sw $v0, " << instr.result << "\n";
            }
            continue;
        }

        if (instr.op == "RETURN") {
            if (!instr.arg1.empty()) {
                ss << loadOperand(instr.arg1, "$v0");
            }
            ss << "    jr $ra\n";
            continue;
        }
    }

    // Program exit syscall
    ss << "    li $v0, 10\n    syscall\n";
    return ss.str();
}

void MIPSCodeGenerator::printMIPS(const std::string& asm_code) const {
    std::cout << "\n========================================================" << std::endl;
    std::cout << "         MIPS32 TARGET ASSEMBLY CODE (.asm)             " << std::endl;
    std::cout << "========================================================" << std::endl;
    std::cout << asm_code << std::endl;
}
